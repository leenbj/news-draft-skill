def policy_whitelist() -> tuple[str, ...]:
    """已收录的政策文件名（不带书名号），用于核对稿件里的引用。"""
    import re as _re
    names = set()
    for item in INDUSTRIES.values():
        for p in item["policy"]:
            m = _re.match(r"《([^》]+)》", p)
            if m:
                names.add(m.group(1))
    return tuple(sorted(names))


def infer_industry(company: str) -> tuple[str, str]:
    """返回 (行业键, 命中的关键词)；识别不出返回 ('通用制造业', '')。"""
    name = (company or "").strip()
    best_key, best_kw = "通用制造业", ""
    for key, kws in INDUSTRY_KEYS:
        for kw in kws:
            if kw in name and len(kw) > len(best_kw):
                best_key, best_kw = key, kw
    return best_key, best_kw


def industry_material(company: str) -> dict:
    """给出这家企业名称对应的行业素材（industry 为 None 表示用了通用兜底）。"""
    key, kw = infer_industry(company)
    item = INDUSTRIES.get(key) or INDUSTRIES["通用制造业"]
    return {
        "key": key,
        "matched_keyword": kw,
        "inferred": bool(kw),
        "name": item["name"],
        "scene": item["scene"],
        "status": list(item["status"]),
        "policy": list(item["policy"]),
        "digital": list(item["digital"]),
    }


